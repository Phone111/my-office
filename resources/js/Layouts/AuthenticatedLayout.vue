// ค่าเริ่มต้น: กางทุกหมวด (เห็นทุกเมนูทันที) — คลิกหัวข้อเพื่อพับเก็บได้ถ้าต้องการ
// จำสถานะกาง/หุบหมวดข้ามการเปลี่ยนหน้า (layout ถูก mount ใหม่ทุกครั้ง) — ใช้ heading เป็น key
const loadExpanded = () => {
    try {
        return JSON.parse(sessionStorage.getItem('sidebarExpanded') || '{}');
    } catch {
        return {};
    }
};
const expandedSections = ref(loadExpanded());
// กางโดยค่าเริ่มต้น ยกเว้นหมวดที่ตั้ง collapsed: true (เช่น รายงาน) — ผู้ใช้กดสลับได้
const keyOf = (i) => sections.value[i]?.heading ?? i;
const isExpanded = (i) => expandedSections.value[keyOf(i)] ?? !sections.value[i]?.collapsed;
const toggleSection = (i) => {
    expandedSections.value[keyOf(i)] = !isExpanded(i);
    sessionStorage.setItem('sidebarExpanded', JSON.stringify(expandedSections.value));
};

// sidebar (มือถือ)
const sidebarOpen = ref(false);

// จำตำแหน่งเลื่อนของเมนู ไม่ให้เด้งขึ้นบนสุดเมื่อเปลี่ยนหน้า (layout ถูก mount ใหม่ทุกครั้ง)
const navRef = ref(null);
const saveNavScroll = () => {
    if (navRef.value) sessionStorage.setItem('sidebarScroll', navRef.value.scrollTop);
};
onMounted(() => {
    const saved = sessionStorage.getItem('sidebarScroll');
    if (navRef.value && saved) navRef.value.scrollTop = parseInt(saved, 10);

    // ดึงตัวเลขแจ้งเตือนใหม่ทุก 45 วิ (เฉพาะตอนแท็บกำลังเปิด)
    notifTimer = setInterval(() => {
        if (document.visibilityState === 'visible') refreshNotifications();
    }, 45000);
});
onUnmounted(() => {
    if (notifTimer) clearInterval(notifTimer);
});
</script>

