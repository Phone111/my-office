// ตัดตัวคั่นกลุ่มย่อย (divider) ที่ไม่มีเมนูตามหลัง (เช่นถูกกรองด้วยสิทธิ์)
const pruneDividers = (items) =>
    items.filter((it, idx) => {
        if (!it.divider) return true;
        const next = items[idx + 1];
        return next && !next.divider;
    });

// กรองรายการตามสิทธิ์ และซ่อนหมวดที่ว่าง
// หมวด "เอกสารรอดำเนินการ" — โชว์ในเมนูซ้ายเฉพาะรายการที่มีงานค้างจริง (count > 0) + มีแถบด้านบนด้วย
const sections = computed(() =>
    menuSections
        .map((s) => {
            const items = s.heading === 'เอกสารรอดำเนินการ'
                ? s.items.filter((i) => hasAccess(i) && badgeVal(i) > 0)
                : s.items.filter(hasAccess);

            return { ...s, items: pruneDividers(items) };
        })
        .filter((s) => s.items.some((i) => !i.divider)),
);

// ===== แถบงานรอดำเนินการ (คิวงานที่รอเราทำ) — ดึงจากหมวด "เอกสารรอดำเนินการ" =====
const pendingItems = computed(() => {
    const sec = menuSections.find((s) => s.heading === 'เอกสารรอดำเนินการ');
    if (!sec) return [];
    return sec.items
        .filter((i) => !i.divider && hasAccess(i) && badgeVal(i) > 0)
        .map((i) => ({ label: i.label, routeName: i.routeName, routeParams: i.routeParams ?? {}, count: badgeVal(i) }));
});
const pendingTotal = computed(() => pendingItems.value.reduce((s, i) => s + i.count, 0));
const PENDING_DISMISS_KEY = 'pendingDismissedTotal';
const pendingDismissed = ref(typeof sessionStorage !== 'undefined' ? Number(sessionStorage.getItem(PENDING_DISMISS_KEY) ?? -1) : -1);
// โชว์เมื่อมีงานค้าง และยอดไม่ตรงกับที่เคยกดซ่อน (มีงานใหม่เข้ามาก็โผล่ใหม่)
const showPendingBar = computed(() => pendingTotal.value > 0 && pendingTotal.value !== pendingDismissed.value);
const dismissPending = () => {
    pendingDismissed.value = pendingTotal.value;
    if (typeof sessionStorage !== 'undefined') sessionStorage.setItem(PENDING_DISMISS_KEY, String(pendingTotal.value));
};

// ค้นหาเมนู — กรองทุกหมวดเป็นลิสต์เดียว (ใช้ผลที่ผ่านสิทธิ์แล้วจาก sections)
const menuSearch = ref('');
const isSearching = computed(() => menuSearch.value.trim().length > 0);
const searchResults = computed(() => {
    const q = menuSearch.value.trim().toLowerCase();
    if (!q) return [];
    const out = [];
    sections.value.forEach((s) => {
        // จับชื่อหมวด (heading) และหัวข้อย่อย (divider) ด้วย ไม่ใช่แค่ชื่อเมนู
        const headingMatch = (s.heading ?? '').toLowerCase().includes(q);
        let divider = '';
        s.items.forEach((i) => {
            if (i.divider) {
                divider = i.divider.toLowerCase();
                return;
            }
            if (i.label.toLowerCase().includes(q) || headingMatch || divider.includes(q)) out.push(i);
        });
    });
    return out;
});

const isCurrent = (routeName) => route().current(routeName);

// active state ที่รองรับทั้ง query param (category/folder) และ path param (class/type ฯลฯ)
// เพื่อแยกเมนูที่ใช้ route เดียวกันแต่ต่าง params ไม่ให้ไฮไลต์พร้อมกัน
const isActiveItem = (item) => {
    if (!route().current(item.routeName)) return false;
    const rp = item.routeParams ?? {};
    const params = new URLSearchParams(page.url.split('?')[1] ?? '');
    // query param แบบมีค่า default (แฟ้มบันทึกเสนอ / หนังสือเวียน)
    if (rp.category) {
        return (params.get('category') ?? 'memo') === rp.category;
    }
    if (rp.folder) {
        return params.get('folder') === rp.folder;
    }
    // path param อื่น ๆ (เช่น class/type ของการเงิน) — เทียบกับ params จริงของ route ปัจจุบัน
    if (Object.keys(rp).length) {
        return route().current(item.routeName, rp);
    }
    return true;
};

// หมวดที่ "กำลังอยู่" — อยู่หน้า hub ของหมวดนั้น หรืออยู่เมนูย่อยในหมวด
const isSectionActive = (sec) => {
    if (sec.slug && page.url.split('?')[0] === '/hub/' + sec.slug) return true;
    return (sec.items ?? []).some((i) => !i.divider && isActiveItem(i));
};

